def fill_table(index, rows, size=19):
    table = original[index]
    trs = table.findall("w:tr", NS)
    assert len(trs) == len(rows) + 1, (index, len(trs), len(rows))
    for tr, values in zip(trs[1:], rows):
        cells = tr.findall("w:tc", NS)
        assert len(cells) == len(values) + 1
        for tc, text in zip(cells[1:], values):
            ps = tc.findall("w:p", NS)
            write_p(ps[0], text, size=size)
            for p in ps[1:]:
                tc.remove(p)
        trpr = tr.find("w:trPr", NS)
        if trpr is not None:
            for height in trpr.findall("w:trHeight", NS):
                trpr.remove(height)
    for tr in trs:
        trpr = tr.find("w:trPr", NS)
        if trpr is None:
            trpr = E.SubElement(tr, tag("trPr"))
        if trpr.find("w:cantSplit", NS) is None:
            E.SubElement(trpr, tag("cantSplit"))
    hp = trs[0].find("w:trPr", NS)
    if hp.find("w:tblHeader", NS) is None:
        E.SubElement(hp, tag("tblHeader"))


