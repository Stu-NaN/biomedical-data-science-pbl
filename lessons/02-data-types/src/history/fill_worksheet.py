def write_p(p, text, size=21):
    ppr = p.find("w:pPr", NS)
    for el in list(p):
        if el is not ppr:
            p.remove(el)
    if ppr is None:
        ppr = E.SubElement(p, tag("pPr"))
    for name in ("spacing", "keepNext", "keepLines"):
        for el in ppr.findall(f"w:{name}", NS):
            ppr.remove(el)
    spacing = E.SubElement(ppr, tag("spacing"))
    spacing.set(tag("after"), "80")
    spacing.set(tag("line"), "280")
    spacing.set(tag("lineRule"), "auto")
    r = E.SubElement(p, tag("r"))
    rp = E.SubElement(r, tag("rPr"))
    fonts = E.SubElement(rp, tag("rFonts"))
    fonts.set(tag("ascii"), "Arial")
    fonts.set(tag("hAnsi"), "Arial")
    fonts.set(tag("eastAsia"), "Microsoft YaHei")
    E.SubElement(rp, tag("sz")).set(tag("val"), str(size))
    E.SubElement(rp, tag("color")).set(tag("val"), "000000")
    t = E.SubElement(r, tag("t"))
    t.text = text
    t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")


